const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"../docs");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
for(const file of ["styles.css","model.js","app.js","manifest.webmanifest","favicon.svg","icon-192.svg","icon-512.svg","sw.js"])assert.ok(fs.existsSync(path.join(root,file)),`${file} ausente`);
for(const id of ["11","12","21","22","31","32","41","42","51","52"])assert.ok(html.includes(`id="nom-i${id}"`),`nom-i${id} ausente`);
for(const id of ["rc1","rc2","rc3","rc4","rc5","assist","calculate-fixed"])assert.ok(html.includes(`id="${id}"`),`${id} ausente`);
for(const id of ["nom-v","rc1","rc2","rc3","rc4","rc5","nom-i11","nom-i12","nom-i21","nom-i22","nom-i31","nom-i32","nom-i41","nom-i42","nom-i51","nom-i52","live-v"]){
  assert.match(html,new RegExp(`id="${id}"[^>]*step="0\\.01"`),`${id} debe variar en centésimas`);
}
for(const id of ["res-i2","res-i3","res-i4","res-i5","res-dv1","res-dv2","res-dv3","res-dv4","res-dv5"])assert.ok(html.includes(`id="${id}"`),`${id} ausente`);
assert.ok(!html.includes("<svg"),"el esquema en vivo no debe mostrarse");
assert.ok(!html.includes('type="range"'),"no debe haber reglas deslizantes");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
assert.ok(app.includes('const ids=["11","12","21","22","31","32","41","42","51","52"]'));
assert.ok(app.includes('id="reo-${id}"'));
assert.ok(app.includes('id="system-r-${id}"'),"cada resistencia del sistema debe ser editable");
assert.ok(app.includes('$("system-r-"+id).addEventListener("input",solve)'),"editar una resistencia debe recalcular la simulación");
assert.ok(app.includes("Resistencia del Sistema R${id}"));
assert.ok(app.includes('id="reo-power-${id}"'));
assert.ok(app.includes("o.currents[id]**2*o.rheostats[id]"));
assert.ok(app.includes('<span class="input-title">Corriente</span>'));
assert.ok(app.includes('>0.00 W</strong>'));
assert.ok(app.includes("value.toFixed(2)"));
assert.ok(!app.includes("Corriente objetivo"));
assert.ok(!app.includes("Potencia del reóstato"));
assert.ok(app.includes('addEventListener("click",computeFixed)'),"el botón debe recalcular directamente");
assert.ok(app.includes("setRheostat(id,0)"),"el recálculo debe reiniciar los reóstatos");
assert.ok(app.includes('$("live-v").value=result.V'),"el ajuste asistido debe aplicar la tensión mínima");
const assisted=app.match(/function assistedAdjustment\(\)\{([\s\S]*?)\n\}/)[1];
assert.ok(!assisted.includes('n("live-v")'),"el ajuste no debe depender del voltaje de trabajo ingresado");
assert.ok(!assisted.includes('n("reo-"'),"el ajuste no debe depender de los reóstatos ingresados");
assert.ok(app.includes('$("target-"+id).value=state.nominal.currents[id]'),"al restaurar, los objetivos deben coincidir con las corrientes medidas");
assert.ok(!app.includes("showModal"),"el recálculo no debe depender de una confirmación adicional");
assert.ok(!html.includes('id="confirm-dialog"'),"el diálogo anterior debe eliminarse");
assert.ok(html.includes('class="measurement-card side-single"'),"las mediciones deben usar la tarjeta técnica");
assert.ok(html.includes('class="field-grid cable-fields"'),"voltaje y cables deben estar agrupados");
assert.ok(html.includes('class="field-grid current-fields"'),"las corrientes deben estar agrupadas");
assert.ok(html.includes("La aplicación obtiene el voltaje mínimo y los reóstatos."),"la interfaz debe indicar que solo requiere las corrientes objetivo");
const worker=fs.readFileSync(path.join(root,"sw.js"),"utf8");
assert.ok(worker.includes('fetch(event.request).then'),"la aplicación debe buscar primero la versión publicada");
assert.ok(worker.includes('client.navigate(client.url)'),"una actualización debe recargar las pestañas abiertas");
const manifest=JSON.parse(fs.readFileSync(path.join(root,"manifest.webmanifest"),"utf8"));
assert.equal(manifest.display,"standalone");
assert.equal(manifest.start_url,"./");
assert.equal(manifest.short_name,"ANODEFLEX 5 1INY");
console.log("Pruebas de la aplicación estática de cinco nodos: correctas");
